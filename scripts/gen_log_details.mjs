// Extracts real source snippets (max 50 lines) for the admin Logs detail view.
// Run: node scripts/gen_log_details.mjs  -> writes web/js/admin/log-snippets.js
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const MAX_LINES = 50;

const TARGETS = {
    analyze_timeout: { file: 'application/analysis_service.py', start: 80, end: 119, errLine: 111 },
    cover_missing: { file: 'services/media_service.py', start: 189, end: 244, errLine: 214 },
    spotify_credentials: { file: 'infrastructure/spotify_adapter.py', start: 34, end: 50, errLine: 45 },
    remote_token: { file: 'main_web.py', start: 81, end: 99, errLine: 93 },
};

const out = {};
for (const [key, t] of Object.entries(TARGETS)) {
    const lines = readFileSync(resolve(ROOT, t.file), 'utf8').split('\n');
    let start = t.start;
    let end = Math.min(t.end, lines.length);
    if (end - start + 1 > MAX_LINES) {
        start = Math.max(1, t.errLine - Math.floor(MAX_LINES / 2));
        end = start + MAX_LINES - 1;
    }
    out[key] = { file: t.file, start, errLine: t.errLine, lines: lines.slice(start - 1, end) };
}

const target = resolve(ROOT, 'web/js/admin/log-snippets.js');
writeFileSync(target, `// Generated by scripts/gen_log_details.mjs — do not edit by hand.\nexport const SNIPPETS = ${JSON.stringify(out, null, 2)};\n`);
console.log(`Wrote ${Object.keys(out).length} snippets to ${target}`);
